// Dictionnaires de l'interface : francais, arabe et anglais, memes cles dans les trois langues
// (un test le verifie). Aucune generation de code : `t(context, cle)` et `tr(cle)`
// (voir `langue.dart`) lisent ces cartes. Les parametres s'ecrivent `{nom}` dans le texte.
//
// Cles de pluriel : `<cle>.zero`, `.un`, `.deux`, `.peu` (3 a 10) et `.beaucoup` (11 et plus),
// choisies par [formePlurielle] ; le francais et l'anglais repetent la meme forme au-dela de
// deux, l'arabe distingue le duel et les nombres de 3 a 10.
//
// Cles `dates.*` : locale `intl` et motifs `DateFormat` par langue ; `format.separateurDecimal`
// pour les moyennes.

