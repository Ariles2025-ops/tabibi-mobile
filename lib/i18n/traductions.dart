/// Forme plurielle d'un nombre : `zero`, `un`, `deux`, `peu` (3 a 10) ou `beaucoup`.
String formePlurielle(int n) {
  if (n <= 0) return 'zero';
  if (n == 1) return 'un';
  if (n == 2) return 'deux';
  return n <= 10 ? 'peu' : 'beaucoup';
}

/// Texte de [cle] dans [langue] (repli sur le francais, puis sur la cle elle-meme, visible dans
/// les tests) ; chaque `{nom}` de [params] est remplace par sa valeur.
String traduire(String langue, String cle, {Map<String, Object?> params = const {}}) {
  final texte = traductions[langue]?[cle] ?? traductions[langueParDefaut]?[cle] ?? cle;
  if (params.isEmpty) return texte;
  var resultat = texte;
  params.forEach((nom, valeur) => resultat = resultat.replaceAll('{$nom}', '$valeur'));
  return resultat;
}

/// Forme plurielle de [cleBase] pour [n] (`{n}` remplace) dans [langue].
String traduirePluriel(String langue, String cleBase, int n) =>
    traduire(langue, '$cleBase.${formePlurielle(n)}', params: {'n': n});

/// Vrai si la cle existe dans le dictionnaire de reference (francais).
bool cleConnue(String cle) => traductions[langueParDefaut]!.containsKey(cle);

